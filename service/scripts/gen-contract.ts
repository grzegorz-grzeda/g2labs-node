// Generates src/contract.generated.ts from the MQTT contract in ../contract:
// the JSON Schemas (for runtime validation), a TypeScript type per schema and
// the topic list. The Docker build sees only service/, so the output is
// committed; test/contract.test.ts fails when it is out of date.
//
//   npm run contract

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

type Schema = Record<string, unknown>;

/** The keywords the contract uses (core keywords only, see contract/). */
const KNOWN_KEYWORDS = new Set([
  '$schema',
  'title',
  'description',
  'type',
  'properties',
  'required',
  'additionalProperties',
  'enum',
  'pattern',
  'minimum',
  'maximum',
]);

const PRIMITIVES: Record<string, string> = {
  string: 'string',
  integer: 'number',
  number: 'number',
  boolean: 'boolean',
  null: 'null',
};

function fail(where: string, msg: string): never {
  throw new Error(`${where}: ${msg}`);
}

function checkKeywords(schema: Schema, where: string): void {
  for (const key of Object.keys(schema)) {
    if (!KNOWN_KEYWORDS.has(key)) fail(where, `keyword "${key}" isn't supported by the generator`);
  }
}

function comment(text: unknown, indent: string): string {
  return typeof text === 'string' ? `${indent}/** ${text} */\n` : '';
}

/** The TypeScript type of a property schema (no nested objects in the contract yet). */
function typeOf(schema: Schema, where: string): string {
  checkKeywords(schema, where);
  if (Array.isArray(schema.enum)) {
    return schema.enum.map((v) => JSON.stringify(v)).join(' | ');
  }
  const types = Array.isArray(schema.type) ? schema.type : [schema.type];
  return types
    .map((t) => (typeof t === 'string' && t in PRIMITIVES ? PRIMITIVES[t] : fail(where, `type ${JSON.stringify(t)} isn't supported`)))
    .join(' | ');
}

function interfaceOf(schema: Schema, where: string): string {
  checkKeywords(schema, where);
  if (schema.type !== 'object') fail(where, 'a payload schema must be an object');
  if (typeof schema.title !== 'string' || !/^[A-Z][A-Za-z0-9]*$/.test(schema.title)) {
    fail(where, 'a payload schema needs a PascalCase title, used as its type name');
  }
  const properties = (schema.properties ?? {}) as Record<string, Schema>;
  const required = new Set((schema.required ?? []) as string[]);
  let out = comment(schema.description, '') + `export interface ${schema.title} {\n`;
  for (const [name, prop] of Object.entries(properties)) {
    out += comment(prop.description, '  ');
    out += `  ${name}${required.has(name) ? '' : '?'}: ${typeOf(prop, `${where} ${name}`)};\n`;
  }
  return out + '}\n';
}

export function generateContract(contractDir: string): string {
  const schemaDir = join(contractDir, 'schemas');
  const files = readdirSync(schemaDir)
    .filter((f) => f.endsWith('.schema.json'))
    .sort();

  let out =
    '// Generated by scripts/gen-contract.ts from contract/ at the repo root.\n' +
    '// Do not edit: change contract/, then run `npm run contract`.\n\n';

  const names: string[] = [];
  for (const file of files) {
    const schema = JSON.parse(readFileSync(join(schemaDir, file), 'utf8')) as Schema;
    out += interfaceOf(schema, file) + '\n';
    names.push(file.replace(/\.schema\.json$/, ''));
    out += `export const ${names.at(-1)}Schema = ${JSON.stringify(schema, null, 2)} as const;\n\n`;
  }

  const topics = JSON.parse(readFileSync(join(contractDir, 'topics.json'), 'utf8')) as {
    topics: { pattern: string; publisher: string; retained: boolean; encoding: string }[];
  };
  const list = topics.topics.map(({ pattern, publisher, retained, encoding }) => ({ pattern, publisher, retained, encoding }));
  out += '/** Every topic of the contract (topics.json). */\n';
  out += `export const topics = ${JSON.stringify(list, null, 2)} as const;\n`;
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const service = fileURLToPath(new URL('../', import.meta.url));
  writeFileSync(join(service, 'src/contract.generated.ts'), generateContract(join(service, '../contract')));
}
